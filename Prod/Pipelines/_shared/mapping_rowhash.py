"""R1 fold-in R1-b: store each target's row hash with the post-INSR builder formula during the one P2 rewrite.

initial_rewrite copies every column unchanged, so a target keeps the hash its builder last wrote. Where INSR changes
the builder's formula and nothing re-runs the builder before R1's rewrite (today: map_problem, BPERF P4), the first
weekly run would see every row as changed and rewrite the table a second time. post_r1_row_hash recomputes that
column with the post-INSR formula during R1's rewrite instead.

The recipes are generated by tools/inventory.py --row-hash (release/row_hash_specs.json lists every target and why it
needs no recompute: formula unchanged, or re-run by an INSR P2 step before R1.P2). No recipe ever covers an R1 column
(mapping_contract.is_r1_column): the backfill owns those, and their STRUCT carries refresh clocks.
"""
import pyspark.sql.functions as F

import mapping_contract as M

# BEGIN GENERATED RECIPES (tools/inventory.py --row-hash)
ROW_HASH_RECIPES = {
    "map_problem": {
        "builder": "map_20_clinical_component_runner._problem_published_hash_columns",
        "column": "MAP_ROW_HASH",
        "exclude": [
            "MAP_ROW_HASH",
            "MAP_REFRESH_DT_TM",
            "ADC_UPDT",
            "PROBLEM_ADC_UPDT",
            "NOMENCLATURE_ADC_UPDT",
            "CODE_VALUE_ADC_UPDT",
            "CALC_ENCNTR_ADC_UPDT",
            "NOMENCLATURE_SOURCE_CHANGE_TS"
        ],
        "exclude_prefixes": [
            "_"
        ],
        "kind": "sha2_json_sorted"
    }
}
# END GENERATED RECIPES


def hash_input_columns(columns, recipe):
    """The columns one recipe hashes, in the builder's order (sorted by name): every column of the row except the
    recipe's exclusions, names with an excluded prefix, and every R1 lane column."""
    excluded = set(recipe["exclude"])
    prefixes = tuple(recipe.get("exclude_prefixes", ()))
    return sorted(c for c in columns
                  if c not in excluded and not (prefixes and c.startswith(prefixes)) and not M.is_r1_column(c))


def _recipe_expression(columns, recipe):
    """The hash expression of one recipe kind over the given columns."""
    if recipe["kind"] == "sha2_json_sorted":
        # The map_20_clinical _stable_hash: sha2 of to_json(struct(...)) with null fields kept.
        return F.sha2(F.to_json(F.struct(*[F.col(c).alias(c) for c in columns]), {"ignoreNullFields": "false"}), 256)
    raise ValueError(f"unknown row-hash recipe kind {recipe['kind']}")


def post_r1_row_hash(df, table):
    """df with its stored row hash recomputed by the post-INSR formula when `table` has a recipe; df unchanged
    otherwise (its stored hash already is the post-INSR formula's value, see release/row_hash_specs.json)."""
    recipe = ROW_HASH_RECIPES.get(table.replace("`", "").split(".")[-1])
    if recipe is None:
        return df
    columns = hash_input_columns(df.columns, recipe)
    return df.withColumn(recipe["column"], _recipe_expression(columns, recipe))


def recomputed_column(table):
    """The column post_r1_row_hash rewrites for `table`, or None (initial_rewrite's guard lets it differ)."""
    recipe = ROW_HASH_RECIPES.get(table.replace("`", "").split(".")[-1])
    return recipe["column"] if recipe else None
